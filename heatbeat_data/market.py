"""Market prices that value the outputs of each heat reuse solution, per US state (plus Israel).

Reads data_pipeline/market_prices.csv directly (no database, no network). The CSV is generated by
`python -m data_pipeline.build_market_prices` from transcribed EIA, USDA, NOAA, CARB, RGGI and
market sources; see docs/MARKET.md for every item, unit and source.

    import heatbeat_data as hd
    hd.market_prices()                         # long DataFrame, all rows
    hd.market_for("US", "TX")                  # {item: value}, state rows over national defaults
    hd.market_for("US", "TX", detail=True)     # {item: {value, low, high, unit, year, is_estimate, source_url, note}}
    hd.site_market("us-tx-abilene-stargate")   # same, looked up from sites.csv, plus the team Excel keys

Team Excel keys (sheet 1, economics block) returned by site_market():
    p_fuel_usd_kwh   displaced heating fuel price, USD per kWh_th (commercial gas boiler)
    p_steam_usd_mwh  value of displaced bleed steam, USD per MWh_th
    p_co2_usd_ton    value of avoided emissions: state compliance carbon price (0 if none), USD per tCO2
    p_dac_credit_usd_ton  45Q credit for DAC with geologic storage (180), USD per tCO2
    ci_fuel_g_kwh    carbon intensity of displaced heat, gCO2 per kWh_th (gas boiler)
p_elec_usd_kwh and ci_grid_g_kwh come from the location database (site.grid); p_water_usd_m3 from
the water data.
"""
from __future__ import annotations

from functools import lru_cache
from pathlib import Path

import pandas as pd

_DIR = Path(__file__).resolve().parents[1] / "data_pipeline"
EXCEL_KEYS = ("p_fuel_usd_kwh", "p_steam_usd_mwh", "p_co2_usd_ton", "p_dac_credit_usd_ton", "ci_fuel_g_kwh")
_DETAIL = ("value", "low", "high", "unit", "year", "category", "is_estimate", "source_id", "source_url", "note")


def _clean(v):
    if isinstance(v, float) and pd.isna(v):
        return None
    return v.item() if hasattr(v, "item") else v


@lru_cache(maxsize=1)
def market_prices() -> pd.DataFrame:
    return pd.read_csv(_DIR / "market_prices.csv", keep_default_na=False, na_values=[""])


def market_for(country_iso2: str, region: str | None = None, detail: bool = False) -> dict:
    """All items for a country and region. Region rows override the national ("*") rows."""
    df = market_prices()
    df = df[df["country_iso2"] == country_iso2]
    if df.empty:
        return {}
    nat = df[df["region"] == "*"]
    reg = df[df["region"] == region] if region else df.iloc[0:0]
    merged = pd.concat([nat, reg]).drop_duplicates("item", keep="last")
    out = {}
    for _, r in merged.iterrows():
        d = {k: _clean(r[k]) for k in _DETAIL}
        d["region"] = r["region"]
        out[r["item"]] = d if detail else d["value"]
    return out


@lru_cache(maxsize=1)
def _sites() -> pd.DataFrame:
    return pd.read_csv(_DIR / "sites.csv")


def site_market(site_id: str, grid_co2_g_kwh: float | None = None, detail: bool = False) -> dict:
    """Market data for one site. With grid_co2_g_kwh (e.g. site.grid['co2_kg_mwh']) the
    carbon intensity of the local heating mix including electric heating is added as
    ci_heat_mix_g_kwh_th."""
    s = _sites()
    row = s[s["site_id"] == site_id]
    if row.empty:
        raise KeyError(f"unknown site {site_id!r}")
    country, region = row.iloc[0]["country_iso2"], row.iloc[0]["region"]
    m = market_for(country, region, detail=True)
    if grid_co2_g_kwh is not None and "heat_mix_gas_pct" in m:
        m["ci_heat_mix_g_kwh_th"] = _mix_ci(m, float(grid_co2_g_kwh))
    if not detail:
        m = {k: (v["value"] if isinstance(v, dict) else v) for k, v in m.items()}
    return m


def _mix_ci(m: dict, grid_g_kwh: float, cop: float = 1.5) -> dict:
    """Home heating mix CI: fossil part from the CSV, electric part = grid CI / cop (estimate)."""
    share = {k: (m.get(f"heat_mix_{k}_pct", {}) or {}).get("value") or 0 for k in ("electricity", "gas", "propane", "oil")}
    fossil = share["gas"] + share["propane"] + share["oil"]
    total = fossil + share["electricity"]
    ci = (fossil * m["ci_heat_fossil_mix_g_kwh_th"]["value"] + share["electricity"] * grid_g_kwh / cop) / total
    return {"value": round(ci, 1), "low": None, "high": None, "unit": "gCO2/kWh_th", "year": 2020,
            "category": "heat_mix", "is_estimate": 1, "source_id": "eia_recs_2020", "region": m["heat_mix_gas_pct"]["region"],
            "source_url": m["heat_mix_gas_pct"]["source_url"],
            "note": f"RECS heating mix; electric heat at grid CI / COP {cop} (estimate)"}


def excel_inputs(site_id: str) -> dict:
    """The team Excel economics keys for a site (plus p_dac_credit_usd_ton)."""
    m = site_market(site_id)
    return {k: m.get(k) for k in EXCEL_KEYS}
